func TestRender(t *testing.T) {
	pub, hk1, hk2 := newPub(t), newPub(t), newPub(t)
	hosts := []Host{
		{Alias: "zeta", HostName: "10.0.0.2", Port: 2222, User: "deploy", PublicKey: pub, HostKeys: []ssh.PublicKey{hk1, hk2}},
		{Alias: "Alpha", HostName: "fd7a::1", PublicKey: pub, HostKeys: []ssh.PublicKey{hk1}},
		{Alias: "bare", HostName: "fd7a::1", PublicKey: pub}, // no pins
	}
	f, err := render(Options{Dir: "/home/a b/hop", AgentSocket: "/home/a b/hop/agent.sock"}, hosts)
	if err != nil {
		t.Fatal(err)
	}

	// Pins are keyed by the lower-cased alias, never by address or port.
	line := func(alias string, k ssh.PublicKey) string {
		return alias + " " + string(ssh.MarshalAuthorizedKey(k))
	}
	wantKnown := "# Generated by hop from pinned host keys. Changes are overwritten.\n" +
		line("alpha", hk1) +
		line("zeta", hk1) + line("zeta", hk2)
	if got := string(f.knownHosts); got != wantKnown {
		t.Errorf("known_hosts mismatch\n got:\n%s\nwant:\n%s", got, wantKnown)
	}
	khName := "known_hosts-" + contentID([]byte(wantKnown))
	if f.knownHostsName != khName || len(khName) != len("known_hosts-")+16 {
		t.Errorf("known_hosts name = %q, want %q", f.knownHostsName, khName)
	}

	pubID := contentID(ssh.MarshalAuthorizedKey(pub)) + ".pub"
	block := func(host, hostName, port, user, alias string) string {
		b := "\nHost " + host + "\n  HostName " + hostName + "\n  Port " + port + "\n"
		if user != "" {
			b += "  User " + user + "\n"
		}
		return b + `  IdentityAgent "/home/a b/hop/agent.sock"
  IdentityFile "/home/a b/hop/keys/` + strings.TrimSuffix(pubID, ".pub") + `"
  IdentitiesOnly yes
  ForwardAgent no
  HostKeyAlias ` + alias + `
  GlobalKnownHostsFile none
  UserKnownHostsFile "/home/a b/hop/` + khName + `"
  StrictHostKeyChecking yes
  UpdateHostKeys no
`
	}
	wantConfig := "# Generated by hop. Changes are overwritten.\n" +
		block("Alpha", "fd7a::1", "22", "", "alpha") +
		block("bare", "fd7a::1", "22", "", "bare") +
		block("zeta", "10.0.0.2", "2222", "deploy", "zeta")
	if got := string(f.config); got != wantConfig {
		t.Errorf("config mismatch\n got:\n%s\nwant:\n%s", got, wantConfig)
	}

	// One key file for the one distinct public key.
	if len(f.pubKeys) != 1 || string(f.pubKeys[pubID]) != string(ssh.MarshalAuthorizedKey(pub)) {
		t.Errorf("unexpected public key files: %v", f.pubKeys)
	}
}

// The config names the key without ".pub", so ssh does not try the public
// key file as a private key when the agent lacks the key. A config written
// before that change names the .pub file, and its generation is still kept.
func TestReferencedFilesAcceptsBothKeyNames(t *testing.T) {
	const id = "0123456789abcdef"
	for _, cfg := range []string{
		"  IdentityFile /home/a/hop/keys/" + id + "\n",
		"  IdentityFile \"/home/a b/hop/keys/" + id + ".pub\"\n",
	} {
		got := referencedFiles([]byte(cfg))
		if len(got) != 1 || !got[id+".pub"] {
			t.Errorf("referencedFiles(%q) = %v, want %s.pub", cfg, got, id)
		}
	}
}

func TestContentIDIsFirst16HexOfSHA256(t *testing.T) {
	sum := sha256.Sum256([]byte("hello"))
	want := hex.EncodeToString(sum[:])[:16]
	if got := contentID([]byte("hello")); got != want {
		t.Errorf("contentID = %q, want %q", got, want)
	}
}

// testOpts returns options for a fresh config directory under a private
// temp dir.
func testOpts(t *testing.T) Options {
	t.Helper()
	opts, _ := testOptsClock(t)
	return opts
}

// fakeClock is the clock behind Options.now in tests. step, if set, is added
// on every reading.
type fakeClock struct {
	mu   sync.Mutex
	t    time.Time
	step time.Duration
}

func (c *fakeClock) now() time.Time {
	c.mu.Lock()
	defer c.mu.Unlock()
	c.t = c.t.Add(c.step)
	return c.t
}

func (c *fakeClock) advance(d time.Duration) {
	c.mu.Lock()
	defer c.mu.Unlock()
	c.t = c.t.Add(d)
}

// graceForTests is the PruneGrace that testOptsClock sets.
const graceForTests = time.Hour

// testOptsClock is testOpts with a clock the test controls and a one hour
// prune grace.
func testOptsClock(t *testing.T) (Options, *fakeClock) {
	t.Helper()
	dir := filepath.Join(t.TempDir(), "hop")
	clk := &fakeClock{t: time.Now()}
	return Options{
		Dir:         dir,
		AgentSocket: filepath.Join(dir, "agent.sock"),
		PruneGrace:  graceForTests,
		now:         clk.now,
	}, clk
}

// names lists the entries of dir that match glob, sorted.
func names(t *testing.T, dir, glob string) []string {
	t.Helper()
	m, err := filepath.Glob(filepath.Join(dir, glob))
	if err != nil {
		t.Fatal(err)
	}
	for i := range m {
		m[i] = filepath.Base(m[i])
	}
	return m
}

func mustWrite(t *testing.T, opts Options, hosts ...Host) {
	t.Helper()
	if err := Write(opts, hosts); err != nil {
		t.Fatal(err)
	}
}

func TestWrite(t *testing.T) {
	opts := testOpts(t)
	dir := opts.Dir
	pubA, pubB := newPub(t), newPub(t)
	hostA := Host{Alias: "a", HostName: "h", PublicKey: pubA, HostKeys: []ssh.PublicKey{newPub(t)}}
	hostB := Host{Alias: "b", HostName: "h", PublicKey: pubB}

	mustWrite(t, opts, hostA, hostB)
	f, err := render(opts, []Host{hostA, hostB})
	if err != nil {
		t.Fatal(err)
	}
	files := []string{"config", f.knownHostsName}
	for name := range f.pubKeys {
		files = append(files, filepath.Join("keys", name))
	}
	for _, name := range files {
		fi, err := os.Stat(filepath.Join(dir, name))
		if err != nil {
			t.Fatal(err)
		}
		if fi.Mode().Perm() != 0o600 {
			t.Errorf("%s mode = %o, want 600", name, fi.Mode().Perm())
		}
	}
	for _, d := range []string{dir, filepath.Join(dir, "keys")} {
		fi, err := os.Stat(d)
		if err != nil {
			t.Fatal(err)
		}
		if fi.Mode().Perm() != 0o700 {
			t.Errorf("%s mode = %o, want 700", d, fi.Mode().Perm())
		}
	}
	// A public key file is named for its content and holds exactly the key line.
	line := ssh.MarshalAuthorizedKey(pubA)
	got, err := os.ReadFile(filepath.Join(dir, "keys", contentID(line)+".pub"))
	if err != nil || !bytes.Equal(got, line) {
		t.Errorf("public key file for host a: %q, %v", got, err)
	}

	// Writing the same input again changes nothing on disk, not even inodes.
	before, _ := os.Stat(filepath.Join(dir, "keys", contentID(line)+".pub"))
	mustWrite(t, opts, hostA, hostB)
	after, _ := os.Stat(filepath.Join(dir, "keys", contentID(line)+".pub"))
	if !os.SameFile(before, after) {
		t.Error("an identical content-addressed file was rewritten")
	}

	for _, d := range []string{dir, filepath.Join(dir, "keys")} {
		for _, n := range names(t, d, "*.tmp*") {
			t.Errorf("leftover temp file %s/%s", d, n)
		}
		for _, n := range names(t, d, ".*tmp*") {
			t.Errorf("leftover temp file %s/%s", d, n)
		}
	}
}

func TestWriteDropsRemovedHostOnceItsGenerationIsOld(t *testing.T) {
	opts, clk := testOptsClock(t)
	hostA := Host{Alias: "a", HostName: "h", PublicKey: newPub(t)}
	hostB := Host{Alias: "b", HostName: "h", PublicKey: newPub(t)}
	bFile := contentID(ssh.MarshalAuthorizedKey(hostB.PublicKey)) + ".pub"

	mustWrite(t, opts, hostA, hostB)
	mustWrite(t, opts, hostA)
	cfg, err := os.ReadFile(filepath.Join(opts.Dir, "config"))
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(cfg), "Host b") {
		t.Error("config still has host b")
	}
	// Host b is gone from the config but the previous config used its key
	// file, so it stays for one more generation.
	if _, err := os.Stat(filepath.Join(opts.Dir, "keys", bFile)); err != nil {
		t.Errorf("previous generation's key file was pruned too early: %v", err)
	}
	clk.advance(2 * graceForTests)
	mustWrite(t, opts, hostA)
	if _, err := os.Stat(filepath.Join(opts.Dir, "keys", bFile)); !os.IsNotExist(err) {
		t.Errorf("key file of host b should be gone once it is past the grace period, stat error = %v", err)
	}
}

// snapshot reads every file below dir.
func snapshot(t *testing.T, dir string) map[string]string {
	t.Helper()
	out := map[string]string{}
	err := filepath.WalkDir(dir, func(p string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		b, err := os.ReadFile(p)
		out[strings.TrimPrefix(p, dir)] = string(b)
		return err
	})
	if err != nil {
		t.Fatal(err)
	}
	return out
}

func TestFailureBeforeConfigRenameKeepsOldGeneration(t *testing.T) {
	opts, clk := testOptsClock(t)
	old := []Host{{Alias: "a", HostName: "h", PublicKey: newPub(t), HostKeys: []ssh.PublicKey{newPub(t)}}}
	mustWrite(t, opts, old...)
	before := snapshot(t, opts.Dir)

	boom := errors.New("injected failure")
	testHookBeforeConfig = func() error {
		// By now the new generation's files are on disk.
		if len(snapshot(t, opts.Dir)) <= len(before) {
			t.Error("new dependencies were not written before the hook ran")
		}
		return boom
	}
	t.Cleanup(func() { testHookBeforeConfig = nil })

	next := []Host{{Alias: "a", HostName: "other", PublicKey: newPub(t), HostKeys: []ssh.PublicKey{newPub(t)}}}
	if err := Write(opts, next); !errors.Is(err, boom) {
		t.Fatalf("Write error = %v, want the injected failure", err)
	}

	after := snapshot(t, opts.Dir)
	for name, content := range before {
		got, ok := after[name]
		if !ok {
			t.Errorf("%s of the old generation is gone", name)
		} else if got != content {
			t.Errorf("%s of the old generation changed", name)
		}
	}
	// The old config still names files that exist.
	for ref := range referencedFiles([]byte(after["/config"])) {
		path := "/" + ref
		if strings.HasSuffix(ref, ".pub") {
			path = "/keys/" + ref
		}
		if _, ok := after[path]; !ok {
			t.Errorf("old config refers to %s, which is missing", ref)
		}
	}

	// The next successful Write sweeps up the orphans of the failed one.
	testHookBeforeConfig = nil
	clk.advance(2 * graceForTests)
	mustWrite(t, opts, old...)
	if got := len(snapshot(t, opts.Dir)); got != len(before) {
		t.Errorf("%d files after recovery, want %d: %v", got, len(before), snapshot(t, opts.Dir))
	}
}

// ownFiles returns the snapshot paths of the dependency files that the
// snapshot's own config refers to.
func ownFiles(snap map[string]string) []string {
	var out []string
	for ref := range referencedFiles([]byte(snap["/config"])) {
		if strings.HasSuffix(ref, ".pub") {
			out = append(out, "/keys/"+ref)
		} else {
			out = append(out, "/"+ref)
		}
	}
	return out
}

func TestPruneKeepsPreviousGenerationOnly(t *testing.T) {
	opts, clk := testOptsClock(t)
	gen := func() []Host {
		return []Host{{Alias: "a", HostName: "h", PublicKey: newPub(t), HostKeys: []ssh.PublicKey{newPub(t)}}}
	}
	count := func() (keys, pins int) {
		return len(names(t, filepath.Join(opts.Dir, "keys"), "*.pub")), len(names(t, opts.Dir, "known_hosts-*"))
	}

	mustWrite(t, opts, gen()...)
	gen1 := snapshot(t, opts.Dir)
	clk.advance(2 * graceForTests)
	mustWrite(t, opts, gen()...)
	gen2 := snapshot(t, opts.Dir)

	// After the second write both generations are on disk.
	if k, p := count(); k != 2 || p != 2 {
		t.Fatalf("after 2 generations: %d key files, %d known_hosts files; want 2 and 2", k, p)
	}
	if len(ownFiles(gen1)) != 2 {
		t.Fatalf("generation 1 config refers to %v, want 1 key file and 1 known_hosts", ownFiles(gen1))
	}
	for _, name := range ownFiles(gen1) {
		if _, ok := gen2[name]; !ok {
			t.Errorf("generation 1 file %s was pruned while it was still the previous generation", name)
		}
	}

	// The third write drops generation 1, which is past the grace period,
	// and keeps 2.
	clk.advance(2 * graceForTests)
	mustWrite(t, opts, gen()...)
	gen3 := snapshot(t, opts.Dir)
	if k, p := count(); k != 2 || p != 2 {
		t.Fatalf("after 3 generations: %d key files, %d known_hosts files; want 2 and 2", k, p)
	}
	for _, name := range ownFiles(gen2) {
		if _, ok := gen3[name]; !ok {
			t.Errorf("generation 2 file %s was pruned while it was the previous generation", name)
		}
	}
	for _, name := range ownFiles(gen1) {
		if _, ok := gen3[name]; ok {
			t.Errorf("generation 1 file %s survived two generations", name)
		}
	}
}

// Two consecutive writes that drop host a must not delete its files while a
// reader of the old generation may still hold them: the grace period decides.
func TestPruneKeepsUnreferencedFilesWithinGrace(t *testing.T) {
	opts, clk := testOptsClock(t)
	hostA := Host{Alias: "a", HostName: "h", PublicKey: newPub(t), HostKeys: []ssh.PublicKey{newPub(t)}}
	hostB := Host{Alias: "b", HostName: "h", PublicKey: newPub(t)}
	fa, err := render(opts, []Host{hostA, hostB})
	if err != nil {
		t.Fatal(err)
	}
	// hostA's own files: its key file, and the known_hosts that only a
	// config with its pins would name.
	aKey := filepath.Join(opts.Dir, "keys", contentID(ssh.MarshalAuthorizedKey(hostA.PublicKey))+".pub")
	aPins := filepath.Join(opts.Dir, fa.knownHostsName)
	exists := func(p string) bool { _, err := os.Stat(p); return err == nil }

	mustWrite(t, opts, hostA, hostB)
	clk.advance(time.Minute)
	mustWrite(t, opts, hostB) // drops a; the previous config still names its files
	clk.advance(time.Minute)
	mustWrite(t, opts, hostB) // neither config names them any more
	for _, p := range []string{aKey, aPins} {
		if !exists(p) {
			t.Errorf("%s was deleted two writes after it was dropped, inside the grace period", filepath.Base(p))
		}
	}

	clk.advance(graceForTests / 2)
	mustWrite(t, opts, hostB)
	for _, p := range []string{aKey, aPins} {
		if !exists(p) {
			t.Errorf("%s was deleted before the grace period ended", filepath.Base(p))
		}
	}

	clk.advance(graceForTests)
	mustWrite(t, opts, hostB)
	for _, p := range []string{aKey, aPins} {
		if exists(p) {
			t.Errorf("%s survived past the grace period", filepath.Base(p))
		}
	}
	// What the config still names is untouched.
	cfg, err := os.ReadFile(filepath.Join(opts.Dir, "config"))
	if err != nil {
		t.Fatal(err)
	}
	for ref := range referencedFiles(cfg) {
		p := filepath.Join(opts.Dir, ref)
		if strings.HasSuffix(ref, ".pub") {
			p = filepath.Join(opts.Dir, "keys", ref)
		}
		if !exists(p) {
			t.Errorf("config refers to %s, which is missing", ref)
		}
	}
}

// A file that is re-referenced after sitting unreferenced is young again: the
// grace period counts from the last config that named it.
func TestReferencedFileGraceRestartsWhenDropped(t *testing.T) {
	opts, clk := testOptsClock(t)
	hostA := Host{Alias: "a", HostName: "h", PublicKey: newPub(t)}
	hostB := Host{Alias: "b", HostName: "h", PublicKey: newPub(t)}
	aKey := filepath.Join(opts.Dir, "keys", contentID(ssh.MarshalAuthorizedKey(hostA.PublicKey))+".pub")

	mustWrite(t, opts, hostA, hostB)
	clk.advance(10 * graceForTests) // a has been in the config for a long time
	mustWrite(t, opts, hostB)       // dropped now
	mustWrite(t, opts, hostB)       // a is unreferenced, but only just
	if _, err := os.Stat(aKey); err != nil {
		t.Errorf("a long-lived file was deleted the moment it was dropped: %v", err)
	}
}

// The previous generation's times must be refreshed before the new config is
// published; otherwise a crash between publishing and refreshing lets the next
// Write prune files a reader of the previous config still needs.
func TestPreviousGenerationIsRefreshedBeforePublish(t *testing.T) {
	opts, clk := testOptsClock(t)
	hostA := Host{Alias: "a", HostName: "h", PublicKey: newPub(t)}
	hostB := Host{Alias: "b", HostName: "h", PublicKey: newPub(t)}
	aKey := filepath.Join(opts.Dir, "keys", contentID(ssh.MarshalAuthorizedKey(hostA.PublicKey))+".pub")

	mustWrite(t, opts, hostA)
	clk.advance(10 * graceForTests) // config A has been current for a long time
	want := clk.now()

	var seen time.Time
	testHookBeforeConfig = func() error {
		fi, err := os.Stat(aKey)
		if err != nil {
			return err
		}
		seen = fi.ModTime()
		return nil
	}
	t.Cleanup(func() { testHookBeforeConfig = nil })

	mustWrite(t, opts, hostB)
	if d := seen.Sub(want); d < -time.Second || d > time.Second {
		t.Errorf("previous generation's mtime at publish = %v, want %v (refreshed before publishing)", seen, want)
	}
}

func TestPruneSweepsOnlyOldTempFiles(t *testing.T) {
	opts, clk := testOptsClock(t)
	host := Host{Alias: "a", HostName: "h", PublicKey: newPub(t)}
	mustWrite(t, opts, host)

	oldTemps := []string{
		filepath.Join(opts.Dir, ".config.tmp111"),
		filepath.Join(opts.Dir, ".known_hosts-0123456789abcdef.tmp222"),
		filepath.Join(opts.Dir, "keys", ".0123456789abcdef.pub.tmp333"),
	}
	freshTemp := filepath.Join(opts.Dir, ".config.tmp444")
	for _, p := range append(oldTemps, freshTemp) {
		if err := os.WriteFile(p, []byte("x"), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	past := clk.now().Add(-2 * graceForTests)
	for _, p := range oldTemps {
		if err := os.Chtimes(p, past, past); err != nil {
			t.Fatal(err)
		}
	}
	fresh := clk.now()
	if err := os.Chtimes(freshTemp, fresh, fresh); err != nil {
		t.Fatal(err)
	}

	mustWrite(t, opts, host)
	for _, p := range oldTemps {
		if _, err := os.Stat(p); !os.IsNotExist(err) {
			t.Errorf("stale temp file %s was not swept: %v", p, err)
		}
	}
	if _, err := os.Stat(freshTemp); err != nil {
		t.Errorf("fresh temp file was swept: %v", err)
	}
	if _, err := os.Stat(filepath.Join(opts.Dir, lockName)); err != nil {
		t.Errorf("lock file is gone: %v", err)
	}
}

// Write must wait for config.lock, which another process (or Write) may hold.
