func newPub(t *testing.T) ssh.PublicKey {
	t.Helper()
	pub, _, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	k, err := ssh.NewPublicKey(pub)
	if err != nil {
		t.Fatal(err)
	}
	return k
}

func TestQuotePath(t *testing.T) {
	tests := []struct {
		in, want string
		wantErr  bool
	}{
		{in: "/home/a/.ssh/hop/config", want: "/home/a/.ssh/hop/config"},
		{in: "/home/a b/hop", want: `"/home/a b/hop"`},
		{in: `/home/a"b/hop`, want: `"/home/a\"b/hop"`},
		{in: `/home/a\b`, want: `"/home/a\\b"`},
		{in: "/home/100%/hop", want: "/home/100%%/hop"},
		{in: "/home/100% off/hop", want: `"/home/100%% off/hop"`},
		{in: "/home/#x/hop", want: `"/home/#x/hop"`},
		{in: "/home/$HOME/hop", wantErr: true},
		{in: "/home/a\nb", wantErr: true},
	}
	for _, tt := range tests {
		got, err := quotePath(tt.in)
		if (err != nil) != tt.wantErr {
			t.Errorf("quotePath(%q) error = %v, wantErr %v", tt.in, err, tt.wantErr)
			continue
		}
		if got != tt.want {
			t.Errorf("quotePath(%q) = %q, want %q", tt.in, got, tt.want)
		}
	}
}

func TestRenderRejectsBadHosts(t *testing.T) {
	good := Host{Alias: "web", HostName: "10.0.0.1", PublicKey: newPub(t)}
	with := func(f func(*Host)) Host { h := good; f(&h); return h }

	tests := []struct {
		name  string
		hosts []Host
	}{
		{"empty alias", []Host{with(func(h *Host) { h.Alias = "" })}},
		{"wildcard alias", []Host{with(func(h *Host) { h.Alias = "*" })}},
		{"alias with space", []Host{with(func(h *Host) { h.Alias = "a b" })}},
		{"alias path traversal", []Host{with(func(h *Host) { h.Alias = "../x" })}},
		{"host name with newline", []Host{with(func(h *Host) { h.HostName = "a\nProxyCommand evil" })}},
		{"host name with percent", []Host{with(func(h *Host) { h.HostName = "%h" })}},
		{"negative port", []Host{with(func(h *Host) { h.Port = -1 })}},
		{"port too large", []Host{with(func(h *Host) { h.Port = 65536 })}},
		{"user with space", []Host{with(func(h *Host) { h.User = "a b" })}},
		{"no public key", []Host{with(func(h *Host) { h.PublicKey = nil })}},
		{"duplicate alias", []Host{good, good}},
		{"duplicate alias, other case", []Host{good, with(func(h *Host) { h.Alias = "WEB" })}},
	}
	opts := Options{Dir: "/tmp/hop", AgentSocket: "/tmp/hop/agent.sock"}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if _, err := render(opts, tt.hosts); err == nil {
				t.Error("render succeeded")
			}
		})
	}
}

